_SEEN = set()


def _mk(instruction, inp, out):
    """入表前按 input 去重；同一 input 只保留第一条"""
    key = inp.strip()
    if key in _SEEN:
        return None
    _SEEN.add(key)
    return {"instruction": instruction, "input": inp, "output": out}


