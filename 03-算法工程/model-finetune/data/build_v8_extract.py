def fix_description(inp, cur_desc, bname, floor):
    """把套话 description 换成具体事件描述

    ★ 判据收紧：只认「纯套话」形态，不认「套话词嵌在具体描述里」。
      例："围栏破损，存在安全隐患" 是好描述（含具体事件），不能当残留；
          "垂直书院存在安全隐患，请注意" 才是套话。
    """
    tpl = [f"{bname}存在安全隐患", f"{bname}存在安全", f"{bname}服务调整",
           f"{bname}请注意时间安排", f"{bname}附近有互助信息发布"]
    if floor:
        tpl += [f"{bname}{floor}楼存在安全隐患", f"{bname}{floor}楼服务调整",
                f"{bname}{floor}楼请注意时间安排"]
    # 允许前缀（如"美术馆存在安全隐患，请注意"）——用 startswith 判纯套话
    generic = any(cur_desc.startswith(t) for t in tpl)
    if not generic:
        # 退一步：整个 description 去掉建筑名/楼层后只剩套话词，也算
        rest = cur_desc
        for t in tpl:
            rest = rest.replace(t, "")
        if rest.strip("，,。 ") in ("", "请注意", "请留意"):
            generic = True
    if not generic:
        return cur_desc

    for kws, excludes, event in DESC_EVENTS:
        if any(k in inp for k in kws) and not any(e in inp for e in excludes):
            b = f"{bname}{floor}楼" if floor else bname
            return f"{b}{event}"
    return cur_desc


