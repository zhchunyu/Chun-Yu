def main():
    src = json.load(open(SRC, encoding="utf-8"))
    print(f"读入 {SRC}: {len(src)} 条")

    # ---- 1. 去重 ----
    seen = set()
    dedup = []
    for x in src:
        key = x["input"].strip()
        if key in seen:
            continue
        seen.add(key)
        dedup.append(x)
    print(f"去重后: {len(dedup)} 条（删 {len(src) - len(dedup)}）")

    # ---- 2. 修 advice + description ----
    fixed_advice = 0
    fixed_desc = 0
    out_rows = []

    for x in dedup:
        inp = x["input"]
        try:
            o = json.loads(x["output"])
        except Exception:
            continue

        bname = o.get("building_name", "")
        floor = o.get("floor")

        new_advice = fix_advice(inp, o.get("advice", ""))
        if new_advice != o.get("advice"):
            fixed_advice += 1
        o["advice"] = new_advice

        new_desc = fix_description(inp, o.get("description", ""), bname, floor)
        if new_desc != o.get("description"):
            fixed_desc += 1
        o["description"] = new_desc

        out_rows.append({
            "instruction": x["instruction"],
            "input": inp,
            "output": json.dumps(o, ensure_ascii=False),
        })

    print(f"修正 advice: {fixed_advice} 条")
    print(f"修正 description: {fixed_desc} 条")

    # ---- 3. 划分训练/评估 ----
    random.shuffle(out_rows)
    n_eval = min(max(120, len(out_rows) // 10), int(len(out_rows) * 0.12))
    ev = out_rows[:n_eval]
    tr = out_rows[n_eval:]

    json.dump(tr, open("v8_extract_train.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    json.dump(ev, open("v8_extract_eval.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    print(f"\n训练集 {len(tr)} 条 → v8_extract_train.json")
    print(f"评估集 {len(ev)} 条 → v8_extract_eval.json")

    # ---- 4. 统计 ----
    types = collections.Counter(json.loads(r["output"])["type"] for r in out_rows)
    print("\n=== 类型分布 ===")
    for k, v in types.most_common():
        print(f"  {k}: {v} ({v / len(out_rows) * 100:.1f}%)")

    adv = collections.Counter(json.loads(r["output"])["advice"] for r in out_rows)
    print(f"\nadvice 去重: {len(adv)} 种")
    print("Top 5 高频 advice:")
    for k, v in adv.most_common(5):
        print(f"  {v:4d}  {k}")

    bad = 0
    for r in out_rows:
        try:
            json.loads(r["output"])
        except Exception:
            bad += 1
    print(f"\nJSON 解析失败: {bad}")


if __name__ == "__main__":
    main()
