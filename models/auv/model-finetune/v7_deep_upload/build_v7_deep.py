def generate_anomaly():
    """热度异常：3 变体（完整 / 只给判定和理由 / 要不要处理）"""
    data = []
    for loc, period, base, days, verdict, reason, adv, key in ANOMALY_CASES:
        days_txt = " / ".join("缺失" if d is None else str(d) for d in days)
        inp = (f"【地点】{loc}\n【时段】{period}\n【基线】{base} 人次\n"
               f"【最近 5 天】{days_txt}")
        out = f"判定：{verdict}。\n\n{reason}\n\n建议：{adv}"

        for item in (
            _mk(INSTRUCTION_ANOMALY, inp, out),
            _mk(INSTRUCTION_ANOMALY, inp + "\n【要求】只给判定和一句话理由",
                f"{verdict}。{_split_first_sentence(reason)}"),
            _mk(INSTRUCTION_ANOMALY, inp + "\n【要求】这条要不要处理？",
                adv),
        ):
            if item:
                data.append(item)
    return data


def generate_queue():
    """等待估算：3 变体（完整 / 只要时长 / 算式与前提）"""
    data = []
    for loc, when, qlen, points, sec, concl, calc, premise, adv, key in QUEUE_CASES:
        inp = (f"【地点】{loc}\n【时刻】{when}\n【当前排队】{qlen} 人\n"
               f"【开放服务点】{points} 个\n【人均服务时长】{sec} 秒")
        out = f"{concl}。\n\n{calc}\n\n注意：{premise}\n\n建议：{adv}"

        for item in (
            _mk(INSTRUCTION_QUEUE, inp, out),
            _mk(INSTRUCTION_QUEUE, inp + "\n【要求】只要预计等待时间，给一个数",
                f"{concl}。{calc}"),
            _mk(INSTRUCTION_QUEUE, inp + "\n【要求】写出算式，并说明这个估计的前提",
                f"{calc}\n\n前提：{premise}"),
        ):
            if item:
                data.append(item)
    return data


def main():
    data = []
    data += generate_spatial()
    data += generate_anomaly()
    data += generate_queue()

    random.shuffle(data)
    n_eval = max(12, len(data) // 10)
    eval_set = data[:n_eval]
    train_set = data[n_eval:]

    tr = os.path.join(HERE, "v7_deep_train.json")
    ev = os.path.join(HERE, "v7_deep_eval.json")
    json.dump(train_set, open(tr, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    json.dump(eval_set, open(ev, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    print(f"训练集: {len(train_set)} 条 -> {tr}")
    print(f"评估集: {len(eval_set)} 条 -> {ev}")
    print(f"合计: {len(data)} 条（去重后）")

    # —— 自检 1：不得出现书名 / 理论名 / 术语 ——
    BAD = ["人性化的城市", "死与生", "雅各布斯", "盖尔", "Gehl", "Jacobs",
           "街道眼", "多样性理论", "金字塔原理", "统计学习方法", "排队论",
           "ISLR", "回归分析", "聚类分析", "方差分析", "边缘效应", "必要性活动",
           "可选活动", "人行道芭蕾", "边界真空"]
    txt = json.dumps(data, ensure_ascii=False)
    hits = [b for b in BAD if b in txt]
    if hits:
        print(f"!! 自检失败，出现禁用词: {hits}")
        raise SystemExit(1)
    print("自检 1 通过：无书名/理论名/术语残留")

    # —— 自检 2：input 不得重复（_mk 已保证，这里复核）——
    inputs = [d["input"] for d in data]
    if len(inputs) != len(set(inputs)):
        print("!! 自检失败：存在重复 input")
        raise SystemExit(1)
    print("自检 2 通过：input 全局唯一")

    # —— 自检 3：三字段齐全 ——
    for d in data:
        if not all(d.get(k) for k in ("instruction", "input", "output")):
            print("!! 自检失败：存在空字段")
            raise SystemExit(1)
    print("自检 3 通过：字段齐全")

    # —— 分块统计 ——
    c = Counter()
    for d in data:
        if "空间诊断" in d["instruction"]:
            c["A 空间行为诊断"] += 1
        elif "通行热度" in d["instruction"]:
            c["B 热度异常判定"] += 1
        else:
            c["C 等待时间估算"] += 1
    for k in sorted(c):
        print(f"  {k}: {c[k]} 条")
    print(f"  案例数: 空间 {len(SPATIAL_CASES)} / 异常 {len(ANOMALY_CASES)} / 排队 {len(QUEUE_CASES)}")


if __name__ == "__main__":
    main()
