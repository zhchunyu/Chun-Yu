"""全园配色重标 V2.4 —— **共享模块，所有阶段共用一份**。

作为 `build_extra` 的**最后一项**执行（必须在所有阶段脚本之后，
因为要改的材质分散在 site / stage1-3 / r0~r5 各处）。

> ★ 为什么必须提成共享模块：
>   这段原先内联在 `build_campus_r5.py` 里 —— 它是**全园**的重标
>   （连 `M_水` / `M_草地` / `M_区_*` 都在内），却只在渲 R5 时生效。
>   结果 R0~R4 的成图用的是**旧配色 + 旧光照**，与 R5 混排时风格割裂。
>   任何"全局约定"写在某一个阶段的脚本里，就是这个下场 —— 见 skill
>   `blender-socket-modeling`「换光照 = 全部历史成图作废」。

用法（`BR_CFG_FILE` 的 json 里）：
    "build_extra": ["build_campus_stage1.py", ..., "build_campus_rN.py",
                    "palette_retune.py"]

==================================================================
★★ V2.4 修复：往"已被连线"的插槽写 default_value 是**静默无效**的
==================================================================
`make_mat(..., noise_scale>0)` 建出来的材质，`Base Color` 插槽上挂着
一条 `Noise → ColorRamp` 连线。而 V2.3 的重标是

    set_in(bsdf, 'Base Color', (r, g, b, 1.0))      # 只写 default_value

—— **连线优先，default_value 被忽略**，而且 `set_in` 把异常吞了，
所以既不报错也没有任何效果。实测本工程 **53 个材质里 32 个中招**，
包括 `M_清水混凝土` / `M_混凝土楼板` / `M_桥面` / `M_广场铺装` / `M_区_*`
这些**占画面最大面积**的材质：它们的成图颜色其实是"建材质时的初始色"，
不是 V2 配色表里的目标色。偏差最大的几个：

    M_桥面      有效 0.393 → 目标 0.258   （Δ 0.136，成图明显偏亮）
    M_清水混凝土  有效 0.249 → 目标 0.368   （Δ 0.119，成图明显偏暗）
    M_区_生活    有效 0.366 → 目标 0.250   （Δ 0.116）

V2.4 的做法：**连线时改 ColorRamp 的端点颜色**，把各端点整体**平移**
（不是直接赋值）到目标色 —— 平移保留端点之间原有的明暗差，也就保住了
那点噪声带来的质感。同时把目标色也写进 default_value，方便别的工具读。

★ 环境变量 `BR_PALETTE_LINKED=0` 可退回旧行为（只做 A/B 对照用）。
★ 现在每次都会打印"常量 X 个 / 连线重标 Y 个"—— **让静默失效不可能再发生**。
★ 坑：`_col` 是 **3 元组**（RGB），ColorRamp 端点是 **4 元组**（RGBA）。
  首版误写成 `for i in range(4)` → `IndexError: tuple index out of range`，
  整个渲染直接崩掉（这次是**响的**失败，比静默失效好）。只能动前 3 通道。

==================================================================
V2.4 补：分区"占位体块" `M_体块_*` 原先整表漏标 ⇒ 曝成纯白盒子
==================================================================
主动视觉巡检（把 63 张做成接触表一次看全）发现 `R4_环廊_鸟瞰` / `R3_书院_鸟瞰`
里有二十来个**纯白盒子**。根因不是几何，是**这张表漏了一组材质**：
`build_campus_site.py` 建的 28 栋分区占位体块（六分区分色），基色 `0.51~0.65`，
**比清水混凝土（0.368）还亮近一倍**，在 `sun_strength 5.8 + exposure +0.20`
下直接曝成纯白 —— 整张鸟瞰读起来像"白模"。

判据：**占位体块应当"比清水混凝土略暗"** —— 它们是"既有 / 待改"的体量，不是新建筑。
· 比真建筑亮 → 变"白模"，抢画面
· 比真建筑暗太多 → 变一排黑块
故取 **0.254~0.324**（约原值 ×0.5），并**保留原来的冷暖色相差异**
（人文/教学/生活偏暖，科技/运动偏冷，实验中性），让它们退回"背景体量"的位置。

★ 这批是**常量材质**（Base Color 无连线），所以落在 `_diag_mats.py`
（只查"被连线覆盖"的材质）的输出**之外** —— 想体检它们要用 `_diag_blk.py`。
"""
import os

import bpy

_RETUNE_VER = 'V2.4'
# 是否处理"Base Color 被连线"的材质。默认处理；置 0 退回 V2.3 的旧行为。
_MODE_LINKED = os.environ.get('BR_PALETTE_LINKED', '1') != '0'

_RETUNE = (
    # ---- 亮场：实墙（V2.2 的 0.330 偏中性，这里再暖一档）----
    ('M_清水混凝土', (0.368, 0.342, 0.300), 0.84, None),
    # ---- 暗线：楼板边带（压暗后"层"才读得出来）----
    ('M_混凝土楼板', (0.196, 0.186, 0.172), 0.88, None),
    ('M_墨灰钢构',   (0.082, 0.084, 0.090), 0.42, 0.82),
    # ---- 窗洞：中深玻璃（读作"窗洞"，不读作"黑面"）----
    ('M_超白玻璃',   (0.120, 0.150, 0.166), 0.090, 0.0),
    # ---- 暖色锚点 ----
    ('M_竹木格栅',   (0.455, 0.278, 0.135), 0.72, None),
    ('M_胶合木',     (0.372, 0.218, 0.098), 0.68, None),
    ('M_铜饰',       (0.520, 0.300, 0.120), 0.30, 1.0),
    # ---- 屋面：★ 全园最深的一档。
    #  两个数字都是为"第五立面"服务的：
    #   · metallic 0.60 → 0.10：钛锌原先是镜面金属，反射的正是蓝天 ——
    #     鸟瞰里近 40% 的画面是屋面，等于把天铺了一地。
    #   · roughness 0.58 → 0.80：**光压金属度不够**。屋面接近水平，
    #     掠射角下菲涅耳反射仍然很强，粗度不提上去，压了金属度也没用 ——
    #     实测把 metallic 从 0.60 压到 0.15 后成图几乎没变，就是这个原因。
    ('M_钛锌屋面板', (0.126, 0.122, 0.114), 0.80, 0.10),
    # ---- 地面：中间调 ----
    ('M_广场铺装',   (0.252, 0.242, 0.222), 0.76, None),
    ('M_庭院铺装',   (0.215, 0.203, 0.183), 0.90, None),
    ('M_中轴铺装',   (0.278, 0.234, 0.180), 0.78, None),
    ('M_步道',       (0.228, 0.216, 0.196), 0.82, None),
    ('M_驳岸石',     (0.232, 0.222, 0.204), 0.90, None),
    ('M_桥面',       (0.258, 0.252, 0.240), 0.74, None),
    ('M_水',         (0.075, 0.122, 0.140), 0.090, None),
    ('M_草地',       (0.112, 0.172, 0.068), 0.93, None),
    ('M_林地',       (0.074, 0.124, 0.050), 0.95, None),
    ('M_土丘草',     (0.124, 0.180, 0.076), 0.92, None),
    # ---- 分区铺装：统一压到 0.22 档，靠色相（而非明度）区分七区 ----
    ('M_区_人文',    (0.244, 0.244, 0.222), 0.86, None),
    ('M_区_科技',    (0.212, 0.232, 0.230), 0.86, None),
    ('M_区_实验',    (0.224, 0.230, 0.220), 0.86, None),
    ('M_区_运动',    (0.206, 0.230, 0.214), 0.86, None),
    ('M_区_教学',    (0.238, 0.240, 0.218), 0.86, None),
    ('M_区_生活',    (0.250, 0.234, 0.212), 0.86, None),
    # ---- 分区"体块占位"（★ V2.4 新增）----
    #   `build_campus_site.py` 建的 28 栋占位体块，**六个分区分色**（暖/冷相间），
    #   是阶段 0~4 的"旧语言语境"。它们原先的基色是 **0.51~0.65** —— 比清水混凝土
    #   （0.368）还亮近一倍，在 `sun_strength 5.8 + exposure +0.20` 下**直接曝成纯白**，
    #   于是 R0~R4 的鸟瞰/远景里散着二十来个白盒子，整张图像"白模"。
    #   ⇒ 统一压到 **0.25~0.32 档**（约原值 ×0.5），**保留原来的冷暖色相差异**
    #     （人文/教学/生活偏暖，科技/运动偏冷，实验中性），
    #   这样它们退回"背景体量"的位置，不再和真建筑抢画面。
    #   ★ 判据：占位体块应当**比清水混凝土略暗** —— 它们是"既有/待改"的体量，
    #     不是新建筑；比真建筑亮就是"白模"，比它暗太多又会变成一排黑块。
    ('M_体块_人文',  (0.324, 0.309, 0.284), 0.84, None),
    ('M_体块_科技',  (0.254, 0.270, 0.286), 0.80, None),
    ('M_体块_教学',  (0.306, 0.296, 0.276), 0.84, None),
    ('M_体块_运动',  (0.276, 0.289, 0.300), 0.80, None),
    ('M_体块_生活',  (0.314, 0.294, 0.273), 0.84, None),
    ('M_体块_实验',  (0.288, 0.285, 0.288), 0.82, None),
)

_TUNED, _MISSING = 0, []
_N_CONST, _N_LINK, _N_SKIP, _LINKED_NAMES = 0, 0, 0, []

for _nm, _col, _rg, _mt in _RETUNE:
    _M = bpy.data.materials.get(_nm)
    if _M is None:
        # 该阶段还没建出这个材质 —— 正常（例如 R0 阶段没有 M_胶合木），跳过即可
        _MISSING.append(_nm)
        continue
    _bsdf = principled(_M)
    _s = _bsdf.inputs.get('Base Color') if _bsdf else None
    if _s is None:
        _MISSING.append(_nm)
        continue

    if _s.is_linked:
        # ---- 插槽被 ColorRamp 连线占着：必须改**连线源头**，写 default_value 无效 ----
        _src = _s.links[0].from_node
        if _src.bl_idname != 'ShaderNodeValToRGB' or not _MODE_LINKED:
            _N_SKIP += 1
            _LINKED_NAMES.append(_nm)
            continue
        _els = list(_src.color_ramp.elements)
        # 注意：_col 是 **3 元组**（RGB），ColorRamp 端点是 **4 元组**（RGBA）
        # ⇒ 只能对前 3 个通道做平移，alpha 原样保留。
        #   （V2.4 首版这里写成了 range(4)，直接 IndexError: tuple index out of range）
        _mean = [sum(e.color[i] for e in _els) / len(_els) for i in range(3)]
        for _e in _els:
            # **平移**而非赋值：保留端点间原有的明暗差（= 保留噪声质感）
            _c = list(_e.color)
            for _i in range(3):
                _c[_i] = min(1.0, max(0.0, _c[_i] + (_col[_i] - _mean[_i])))
            _e.color = tuple(_c)
        set_in(_bsdf, 'Base Color', (_col[0], _col[1], _col[2], 1.0))
        _N_LINK += 1
    else:
        set_in(_bsdf, 'Base Color', (_col[0], _col[1], _col[2], 1.0))
        _N_CONST += 1

    if _rg is not None:
        set_in(_bsdf, 'Roughness', _rg)
    if _mt is not None:
        set_in(_bsdf, 'Metallic', _mt)
    _TUNED += 1

print('[PALETTE] 配色重标 %s：%d/%d 个材质已改（墙 0.368 / 玻璃 0.120 / '
      '楼板 0.196 / 屋面 0.126·金属度 0.10 / 地面 0.21~0.28）%s'
      % (_RETUNE_VER, _TUNED, len(_RETUNE),
         ('；本阶段未建：' + ' '.join(_MISSING)) if _MISSING else ''))
print('[PALETTE]   Base Color 为常量 %d 个 ／ 由 ColorRamp 连线驱动 %d 个'
      % (_N_CONST, _N_LINK))
if _N_SKIP:
    # ★ 这一行是防"静默失效"复发的哨兵：出现它说明重标没落到这些材质上
    print('[PALETTE]   ⚠ 因连线被跳过 %d 个（BR_PALETTE_LINKED=0 或连线源不是 ColorRamp）：%s'
          % (_N_SKIP, ' '.join(_LINKED_NAMES)))
