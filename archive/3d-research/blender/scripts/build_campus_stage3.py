# 3. 书院组团 A / B / C —— 回字形院落（三栋同构，参数化）
# ==================================================================
def academy(cx, cy, tag):
    """回字形书院：北翼主楼最高，东西厢房次之，南翼门房最低，中间留内院。

    屋面用**悬山**（两坡 + 垂直山面）：把 roof_ring 的 hw_in 与 hw_out 取**同一个值**，
    长边方向就不产生坡度，两端自然落成垂直山面 —— 这才是长条殿堂的形制。
    首版把内环收成 48×8 的"小矩形"，长边方向也去放坡，整个屋顶被压成
    "平顶 + 一圈薄檐"，鸟瞰看四栋书院全是没有屋顶的白盒子。
    另外内环 Z 必须高出墙顶 ≥1.2 m，否则墙顶会从屋面里钻出来（阶段 1 的老坑）；
    出檐统一 5.5 m，檐口正好悬在台基外 1.5~2.5 m。
    """
    s, t, r, g = [], [], [], []
    s.append(box(cx, cy, 112.0, 78.0, 0.80, GZ))                     # 台基
    # 北翼主楼（108×22，墙顶 +15.00）
    _ny = cy + 24.0
    t.append(box(cx, _ny, 108.0, 22.0, 11.20, GZ + 0.80))
    r.append(roof_ring(cx, _ny, 55.0, 11.0, GZ + 16.20, 55.0, 16.5, GZ + 11.60,
                       th=0.42, n=8, lift=0.78))
    # 南翼门房（108×16，墙顶 +11.80）
    _sy = cy - 28.0
    t.append(box(cx, _sy, 108.0, 16.0, 8.00, GZ + 0.80))
    r.append(roof_ring(cx, _sy, 55.0, 8.0, GZ + 13.00, 55.0, 13.5, GZ + 8.80,
                       th=0.38, n=8, lift=0.68))
    # 东西厢房（18×46，墙顶 +13.00）
    for _e in (-1.0, 1.0):
        _ex = cx + _e * 43.0
        t.append(box(_ex, cy, 18.0, 46.0, 9.20, GZ + 0.80))
        r.append(roof_ring(_ex, cy, 9.0, 24.0, GZ + 14.20, 14.5, 24.0, GZ + 9.60,
                           th=0.38, n=8, lift=0.68))
    # 内院铺装 + 十字步道
    s.append(round_rect(cx - 28.0, cy - 14.0, cx + 28.0, cy + 12.0, 3.0, GZ + 0.86))
    # 主楼门窗
    for _i in range(5):
        g.append(box(cx - 40.0 + _i * 20.0, _ny - 11.4, 9.0, 0.8, 6.4, GZ + 3.60))
    emit_to(f'BLD_人文_Academy_{tag}_台基', M_STONE, C_BLD, s)
    emit_to(f'BLD_人文_Academy_{tag}_主体', M_WALL, C_BLD, t)
    emit_to(f'BLD_人文_Academy_{tag}_屋面', M_ROOF, C_BLD, r, recalc=False)
    emit_to(f'BLD_人文_Academy_{tag}_门窗', M_WIN, C_BLD, g)


for _ax, _ay, _tg in ((-105.6, 201.6, 'A'), (105.6, 201.6, 'B'), (115.2, 638.4, 'C')):
    academy(_ax, _ay, _tg)


