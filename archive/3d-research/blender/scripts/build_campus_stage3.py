# 1. 大礼堂 —— 中轴西侧，庄重的重檐大殿
# ==================================================================
# 平面 134×100 太大，单层屋面做不陡（进深 50 m 要 28° 得起 27 m 高，
# 会盖过图书馆）。改用**三层檐**把大屋面拆小，既保住层次又不抢天际线。
# 台基宽度定 134 而不是 142：中轴两侧的大礼堂（西）与美术馆（东）中心都在
# |X| = 84，只有台基同宽，两边**离中轴的距离**才相等（各 17 m），
# 中轴视角才是真对称。142 时西侧会多压 4 m 到御道上。
# ★ X 与 R3 保持一致（−88.0）：stage3 这一版的大礼堂随后会被 R3 整体拆除重建，
#   但坐标若不同步，将来一旦有人把 R3 的拆除清单改窄，就会**同时出现两座大礼堂**
#   且位置错开 4 m —— 这类"过期坐标"是最难查的坑，宁可现在就对齐。
AX0, AY0 = -88.0, 338.4

_as, _at, _ar, _ag, _aw = [], [], [], [], []

# ---- 台基三层 ----
for _w, _d, _z0 in ((134.0, 100.0, 0.00), (128.0, 94.0, 1.80), (122.0, 88.0, 3.60)):
    _as.append(box(AX0, AY0, _w, _d, 1.80, GZ + _z0))

# ---- 南向大台阶：30 级，正好爬满 5.40 m 台基 ----
_ST_N, _ST_R, _ST_T = 30, 0.18, 0.42
for _i in range(_ST_N):
    _as.append(box(AX0, AY0 - 46.0 - (_ST_N - 1 - _i) * _ST_T,
                   64.0, _ST_T, _ST_R, GZ + _i * _ST_R))
# 台阶两侧的垂带石
for _s in (-1.0, 1.0):
    _as.append(box(AX0 + _s * 33.5, AY0 - 46.0 - _ST_N * _ST_T * 0.5,
                   3.0, _ST_N * _ST_T, 5.40, GZ))

# ---- 主体三层 + 三层檐 ----
_at.append(box(AX0, AY0, 114.0, 76.0, 10.80, GZ + 5.40))            # 一层
_ar.append(roof_ring(AX0, AY0, 52.0, 33.0, GZ + 17.60, 62.0, 43.0, GZ + 14.60,
                     th=0.46, n=8, lift=0.95))                      # 下檐
_at.append(box(AX0, AY0, 100.0, 62.0, 7.80, GZ + 16.20))            # 二层
_ar.append(roof_ring(AX0, AY0, 45.0, 26.0, GZ + 25.20, 55.0, 36.0, GZ + 22.20,
                     th=0.42, n=8, lift=0.85))                      # 上檐
_at.append(box(AX0, AY0, 86.0, 48.0, 5.40, GZ + 24.00))             # 三层
# 大屋顶内环从 38.00 抬到 40.60：高差 8.6 → 11.2 m，正面坡 14.6° → 20.4°。
# 首版 38.00 时屋面几乎是块水平板，正立面看过去像"搭了一张大桌板"。
# 内环半深 0.80 保持 —— 那就是正脊的位置，不能宽。
_ar.append(roof_ring(AX0, AY0, 17.0, 0.80, GZ + 40.60, 50.0, 31.0, GZ + 29.40,
                     th=0.52, n=8, lift=1.30))                      # 大屋顶

# ---- 正脊 + 鸱吻 ----
_ag.append(box(AX0, AY0, 34.0, 1.80, 1.30, GZ + 40.60))
for _s in (-1.0, 1.0):
    _ag.append(box(AX0 + _s * 17.0, AY0, 3.40, 3.00, 2.20, GZ + 40.60))

# ---- 南立面门窗（一层 7 樘，贴在南墙外皮） ----
for _i in range(7):
    _x = AX0 - 45.0 + _i * 15.0
    _aw.append(box(_x, AY0 - 38.4, 8.00, 0.80, 7.20, GZ + 8.00))
# 二三层窗带
for _w, _d, _z0, _h in ((100.0, 62.0, 16.20, 7.80), (86.0, 48.0, 24.00, 5.40)):
    _aw.append(box(AX0, AY0, _w - 4.0, _d - 4.0, _h * 0.34, GZ + _z0 + _h * 0.36))

emit_to('BLD_人文_Auditorium_台基', M_STONE, C_BLD, _as)
