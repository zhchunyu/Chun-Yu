# 现在：体块收到 44×48 / 34×40 / 30×34，改用**四坡攒尖**
# （mid=0.62 让屋面下陡上缓，压出中式"举折"感），屋顶高取体块高的 ~45%。
_MB = ((-16.0, 6.0, 44.0, 48.0, 13.20, 25.0, 10.00),
       (26.0, -8.0, 34.0, 40.0, 10.40, 19.0, 8.60),
       (-10.0, -44.0, 30.0, 34.0, 8.00, 16.5, 6.60))
