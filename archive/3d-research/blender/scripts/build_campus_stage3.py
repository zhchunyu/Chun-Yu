# 2. 美术馆 —— 中轴东侧，几何错落的坡顶体块
# ==================================================================
# 语汇取自苏州博物馆：白墙 + 深色压边 + 几何化的坡顶，
# 用三个高低错落的体块避免"一个大盒子"。
MX0, MY0 = 84.0, 338.4

_ms, _mw, _mr, _me = [], [], [], []
_ms.append(box(MX0, MY0, 134.0, 100.0, 1.20, GZ))                   # 台基

# 三个体块：(dx, dy, w, d, h, 屋面底环半宽, 屋面高)
# 首版体块做到 70×86，再配 20° 出檐的坡顶 —— 平面一大坡就必然平，
# 而且外环 Z 写成 `_h + 1.90 - 0.70` 比内环 Z（`_zr`）还高 1.0 m，
