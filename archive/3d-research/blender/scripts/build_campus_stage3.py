# 4. 钟楼 —— 方形三层楼阁 + 重檐 + 攒尖宝顶
# ==================================================================
# 高度刻意压到 32 m：中轴尽端已有 80.6 m 的镇山塔，
# 钟楼是它的"副题"，抢高度会把中轴的天际线打散。
#
# 首版实拍暴露三个问题（P3_钟楼）：
#   ① 四面开洞 4.20×5.77 是**近方形**，远看像四块大玻璃，不像门；
#      中式券门是竖长矩形，宽高比约 1:2 → 收到 2.80×5.60 / 2.30×3.00 / 1.90×2.40
#   ② 腰檐出檐 5.0 m、坡 21.8° → 像"荷叶/盘子"，收到出檐 3.5 / 3.1 m、坡 32°
#   ③ 宝顶 0.62 m 太小几乎看不见 → 放大到 1.10 m 座 + 0.62 m 珠
# 另外补一圈**朱漆额枋**：楼身顶与檐底之间有 1.2 m 空档（檐悬空），
# 填上朱漆带之后就成了"白墙 + 红枋 + 深檐"的经典楼阁配色。
BX0, BY0 = -115.2, 638.4

_bs, _bt, _br, _bg, _bf = [], [], [], [], []
_bs.append(box(BX0, BY0, 40.0, 40.0, 1.50, GZ))                      # 台基
_bs.append(box(BX0, BY0, 36.0, 36.0, 0.40, GZ + 1.50))               # 台面压边
for _w, _z0, _h in ((26.0, 1.90, 11.10), (22.0, 14.60, 5.40),
                    (18.0, 21.20, 4.40)):
    _bt.append(box(BX0, BY0, _w, _w, _h, GZ + _z0))                  # 三层楼身
    # 朱漆额枋：正好落在「楼身顶 → 檐底」那 1.2 m 空档里，出挑 0.4
    _bf.append(box(BX0, BY0, _w + 0.80, _w + 0.80, 1.20, GZ + _z0 + _h))
_br.append(roof_ring(BX0, BY0, 11.5, 11.5, GZ + 14.60, 15.0, 15.0, GZ + 12.40,
                     th=0.40, n=8, lift=0.62))                       # 腰檐一
_br.append(roof_ring(BX0, BY0, 9.5, 9.5, GZ + 21.20, 12.6, 12.6, GZ + 19.20,
                     th=0.36, n=8, lift=0.54))                       # 腰檐二
_br.append(pyramid_roof(BX0, BY0, 12.0, 12.0, GZ + 25.60, 6.60,
                        n=8, mid=0.58, mid_k=0.52, lift=0.62))       # 攒尖
_bg.append(disc(BX0, BY0, 1.10, GZ + 32.20, th=0.70, n=12))          # 宝顶座
_bg.append(disc(BX0, BY0, 0.62, GZ + 32.90, th=0.55, n=12))          # 宝珠
# 楼身四面开门洞（每层各一）
for _z0, _h, _w, _dw, _dh, _dz in ((1.90, 11.10, 26.0, 2.80, 5.60, 0.60),
                                   (14.60, 5.40, 22.0, 2.30, 3.00, 0.70),
                                   (21.20, 4.40, 18.0, 1.90, 2.40, 0.70)):
    for _e in (-1.0, 1.0):
        _bg.append(box(BX0 + _e * (_w * 0.5 - 0.3), BY0, 0.70, _dw, _dh,
                       GZ + _z0 + _dz))
        _bg.append(box(BX0, BY0 + _e * (_w * 0.5 - 0.3), _dw, 0.70, _dh,
                       GZ + _z0 + _dz))

emit_to('BLD_人文_Bell_Tower_台基', M_STONE, C_BLD, _bs)
emit_to('BLD_人文_Bell_Tower_楼身', M_TOWER_WALL, C_BLD, _bt)
emit_to('BLD_人文_Bell_Tower_额枋', M_TIMBER, C_BLD, _bf)
emit_to('BLD_人文_Bell_Tower_屋面', M_ROOF, C_BLD, _br, recalc=False)
emit_to('BLD_人文_Bell_Tower_门窗', M_WIN, C_BLD, _bg)

print(f'[stage3] 大礼堂 正脊 {GZ + 41.90:.2f} m / 美术馆最高顶 {GZ + 25.10:.2f} m')
print(f'[stage3] 书院 三栋（北翼脊 {GZ + 16.20:.2f} m）/ 钟楼顶 {GZ + 33.45:.2f} m')
