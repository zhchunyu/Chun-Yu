"""R0 阶段限定范围清障 —— 只删**旧语言建筑构件**，一个场地对象都不碰。

> ★ 清障边界（唯一判据）：**V2 已定最终处置为"拆除 / 取消"的旧语言构件才删**；
>   "改造"（原地重建为新语言）的一律**保留旧版作为"改造前"语境**。
>
>   | 构件 | V2 处置 | R0 是否清 |
>   | --- | --- | --- |
>   | 校门牌坊群 / 东西阙 / 石狮 | 阶段 2 **拆除**重做 | ✅ 删 |
>   | 明堂地雕 / 灯柱 / 灯亭 | 明堂 → 下沉智谷 | ✅ 删 |
>   | 案山方亭 | 拆丘顶仿古方亭 → R12 观景平台 | ✅ 删 |
>   | **钟楼 `BLD_人文_Bell_Tower_`** | R3 **取消**（不重建） | ✅ 删 |
>   | 图书馆 `BLD_人文_Library_*` | R2 **改造**（保留台基） | ❌ 留（"改造前"） |
>   | 大礼堂 / 美术馆 / 书院 | R3 **改造** | ❌ 留（"改造前"） |
>
> ★ 为什么 R0 要单独一份，而不是直接复用 `build_campus_r1.py` 的拆除块：
>   r1 的 `_DROP` 里除了建筑构件，还含 **7 个"待重建"场地对象**
>   （`SITE_门区广场` / `SITE_半岛地形` / `SITE_水面` / `SITE_分区_中轴人文区` /
>    `SITE_中轴大道` / `SITE_广场与平台` / `SITE_步道` / `SITE_御道分格` /
>    `SITE_中轴灯柱` / `SITE_中轴灯罩`）—— 因为 R1 会在原地重建山门与下沉智谷。
>   而 **R0 阶段不重建任何场地**，照搬会在地面上挖出洞。
>   ⇒ R0 只取其中"纯建筑 + 独立构筑物"的子集。
>
> ★ 为什么 R0 需要清障：
>   R0 是**语言样板（gate）**，成图里必须看得清新塔本身。未清障时：
>     `R0_垂直书院_正立面` —— 机位在 X=−340 / Y=648 向东正视，而 **钟楼
>        （X≈−98~−126, Y≈631~656）正好立在塔与相机之间**，把塔身下半整个遮住
>        （`diag_ray.py` 实测：像素 (667,1000) 命中 `BLD_人文_Bell_Tower_额枋`，
>         (430,1150) 命中 `..._台基`）；旁边还有 `BLD_校门_阙_*`（朱红阑额 + 黛瓦坡顶）；
>     `R0_垂直书院_中轴` / `_透视` —— 前景整片是牌坊群；
>     `R0_垂直书院_空中庭院` —— 被旧楼阁大屋顶压住画边。
>   （"新塔 × 旧语境"的对照版已归档 `08-交付与归档/renders_20260921_R0_旧语境版/`）
>
> ★ 与 r1 / r3 的一致性：本表是 r1 `_DROP` 的建筑子集 + r3 `_DROP` 中的钟楼。
>   若 r1/r3 将来新增"拆除/取消"类构件，这里要同步补上。

用法：放进 `r0.json` 的 `build_extra`，排在 `build_campus_r0.py` **之后**、
     `palette_retune.py` **之前**（`make_render_configs.py` 的 `STAGE_EXTRA` 已自动插入）。
"""
import bpy

_DROP = (
    # ---- 校门牌坊群（4 个：木构 / 石作 / 屋面 / 脊饰）—— V2 阶段 2 拆除重做 ----
    'BLD_校门_牌坊_',
    # ---- 东西阙（3 个：石作 / 屋面 / 宝顶）----
    'BLD_校门_阙_',
    'BLD_校门_石狮',
    # ---- 明堂广场：中央同心圆铺装纹样 + 四角灯柱灯亭 ----
    #   地雕是 GZ+0.075 的薄层（band + cap），压在场地铺装之上，
    #   删掉只露出下层铺装，不会开洞；灯柱/灯亭是独立构筑物。
    'SITE_明堂地雕',
    'SITE_明堂灯柱',
    'SITE_明堂灯亭',
    # ---- 案山方亭（4 个：石作 / 木构 / 屋面 / 宝顶）----
    #   V2 处置"拆丘顶仿古方亭"，R1 改为 R12 圆形观景平台（台面 Z 12.60）
    'BLD_案山_亭_',
    # ---- 钟楼（5 个）—— R3 定为**取消**（不重建），且正好挡在塔的西侧正立面前 ----
    'BLD_人文_Bell_Tower_',
)

_n = 0
for _ob in list(bpy.data.objects):
    if any(_ob.name.startswith(_p) for _p in _DROP):
        _me = _ob.data
        bpy.data.objects.remove(_ob, do_unlink=True)
        if _me is not None and _me.users == 0:
            bpy.data.meshes.remove(_me)
        _n += 1

print(f'[R0-CLEAR] 已移除旧语言建筑构件 {_n} 个'
      f'（牌坊群 / 阙 / 石狮 / 明堂地雕·灯柱·灯亭 / 案山亭 / 钟楼）；'
      f'场地对象与"改造类"旧楼（图书馆 / 大礼堂 / 美术馆 / 书院）全部保留')
